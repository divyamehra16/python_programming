
# maths-module

import math
print(math.sqrt(36))
print(math.ceil(22.5))      # round "up" to nearest integer
print(math.floor(22.5))     # round "down" to nearest integer
print(round(22.345,2))  # round to which decimal place --> -ve argument
                        # for +ve argument --> integer part round off
print(math.pi)
print(math.e)
print(math.pow(2,3))
print(math.log(100)) # log base e --> by default
print(math.log(100,10)) # log base 10
#trigo
print(math.sin(math.radians(30)))
print(math.cos(math.radians(30)))
print(math.tan(45*(math.pi/180)))
# inverse trigo
print(math.degrees(math.atan(1)))       # atan --> inverse of tan
